package com.garward.wurmmodloader.mods.materialsystem;

/**
 * Material rarity tiers.
 *
 * @author Power Fantasy RPG Team
 * @version 1.0.0
 */
public enum MaterialTier {
    /**
     * Common materials from basic creatures.
     * Wolf Fang, Bear Claw, Spider Venom, etc.
     */
    COMMON,

    /**
     * Rare materials from champions and uniques.
     * Champion Heart, Dragon Scale, etc.
     */
    RARE,

    /**
     * Legendary materials from Titans only.
     * Ifrit Core, Frozen Heart, Verdant Seed, Void Shard.
     */
    LEGENDARY
}
