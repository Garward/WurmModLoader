package com.garward.wurmmodloader.mods.materialsystem;

/**
 * Special effects granted by legendary materials.
 *
 * @author Power Fantasy RPG Team
 * @version 1.0.0
 */
public enum SpecialEffect {
    /** No special effect */
    NONE,

    /** Verdant Seed - heal on hit */
    LIFESTEAL,

    /** Void Shard - chance to fear enemy */
    FEAR,

    /** Ifrit Core - DoT fire damage */
    BURN,

    /** Frozen Heart - chance to slow enemy */
    FREEZE,

    /** Spider Venom - DoT poison damage */
    POISON
}
